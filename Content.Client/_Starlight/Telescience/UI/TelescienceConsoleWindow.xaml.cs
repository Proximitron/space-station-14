using System.Globalization;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._Starlight.Telescience;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

// ReSharper disable CheckNamespace
namespace Content.Client._Starlight.Telescience.UI;

[GenerateTypedNameReferences]
public sealed partial class TelescienceConsoleWindow : FancyWindow
{
    private int _roundId;
    private int _maxTries = 8;
    private int _triesRemaining = 8;
    private bool _roundOver;
    private Vector2? _selectedCoordinate;
    private TelescienceInteractionMode _mode;
    private readonly ButtonGroup _modeButtons = new();

    public event Action<Vector2, TelescienceInteractionMode>? InteractionRequested;
    public event Action? NewRoundRequested;

    public TelescienceConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        RoundLabel.Text = Loc.GetString("telescience-console-round", ("round", 1));
        TriesLabel.Text = Loc.GetString("telescience-console-tries", ("remaining", 8), ("total", 8));
        CoordinateLabel.Text = Loc.GetString("telescience-console-no-coordinate");
        TargetLabel.Visible = false;
        Instructions.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("telescience-console-instructions")));
        SetStatus("telescience-console-select-coordinate");

        PingMode.Group = _modeButtons;
        PinpointMode.Group = _modeButtons;
        Map.CoordinateSelected += SelectCoordinate;
        PingMode.OnPressed += _ => SetMode(TelescienceInteractionMode.Ping);
        PinpointMode.OnPressed += _ => SetMode(TelescienceInteractionMode.Pinpoint);
        ExecuteButton.OnPressed += _ => ExecuteInteraction();
        NewRoundButton.OnPressed += _ => NewRoundRequested?.Invoke();

        SetMode(TelescienceInteractionMode.Ping);
        UpdateActions();
    }

    public void SetState(TelescienceConsoleBuiState state)
    {
        var newRound = _roundId != state.RoundId;
        _roundId = state.RoundId;
        _maxTries = state.MaxTries;
        _triesRemaining = state.TriesRemaining;
        _roundOver = state.RoundOver;
        RoundLabel.Text = Loc.GetString("telescience-console-round", ("round", state.RoundId));
        TriesLabel.Text = Loc.GetString("telescience-console-tries",
            ("remaining", state.TriesRemaining),
            ("total", state.MaxTries));
        PingOvershootLabel.Text = Loc.GetString("telescience-console-ping-overshoot",
            ("min", FormatNumber(state.MinPingOvershoot)),
            ("max", FormatNumber(state.MaxPingOvershoot)));
        PinpointRadiusLabel.Text = Loc.GetString("telescience-console-pinpoint-radius",
            ("radius", FormatNumber(state.PinpointRadius)));

        if (newRound)
        {
            _selectedCoordinate = null;
            CoordinateLabel.Text = Loc.GetString("telescience-console-no-coordinate");
            SetStatus("telescience-console-select-coordinate");
        }
        else if (state.RoundOver)
            SetStatus(state.RevealedTarget.HasValue
                ? "telescience-console-target-found"
                : "telescience-console-no-tries");

        Map.SetState(state.RoundId, state.History, state.RevealedTarget, state.PinpointRadius);
        RefreshHistory(state.History);
        TargetLabel.Visible = state.RevealedTarget.HasValue;
        if (state.RevealedTarget is { } revealedTarget)
        {
            TargetLabel.Text = Loc.GetString("telescience-console-target-coordinate",
                ("x", FormatCoordinate(revealedTarget.X)),
                ("y", FormatCoordinate(revealedTarget.Y)));
        }

        NewRoundButton.Visible = state.RoundOver;
        UpdateActions();
    }

    public void ShowRejection(TelescienceActionRejection reason)
    {
        var key = reason switch
        {
            TelescienceActionRejection.InvalidCoordinate => "telescience-console-reject-coordinate",
            TelescienceActionRejection.InvalidMode => "telescience-console-reject-mode",
            TelescienceActionRejection.RoundNotOver => "telescience-console-reject-round-active",
            TelescienceActionRejection.RoundOver => "telescience-console-reject-round-over",
            TelescienceActionRejection.InvalidConfiguration => "telescience-console-reject-configuration",
            _ => "telescience-console-reject-mode",
        };
        SetStatus(key);
    }

    private void SelectCoordinate(Vector2 coordinate)
    {
        _selectedCoordinate = coordinate;
        CoordinateLabel.Text = Loc.GetString("telescience-console-coordinate",
            ("x", FormatCoordinate(coordinate.X)),
            ("y", FormatCoordinate(coordinate.Y)));
        SetStatus("telescience-console-coordinate-selected");
        UpdateActions();
    }

    private void SetMode(TelescienceInteractionMode mode)
    {
        _mode = mode;
        Map.SetMode(mode);
        PingMode.Pressed = mode == TelescienceInteractionMode.Ping;
        PinpointMode.Pressed = mode == TelescienceInteractionMode.Pinpoint;
        ExecuteButton.Text = Loc.GetString(mode == TelescienceInteractionMode.Ping
            ? "telescience-console-send-ping"
            : "telescience-console-send-pinpoint");
        UpdateActions();
    }

    private void ExecuteInteraction()
    {
        if (_roundOver || _selectedCoordinate is not { } coordinate)
            return;

        InteractionRequested?.Invoke(coordinate, _mode);
        _selectedCoordinate = null;
        Map.ClearSelection();
        CoordinateLabel.Text = Loc.GetString("telescience-console-no-coordinate");
        SetStatus("telescience-console-ping-sent");
        UpdateActions();
    }

    private void RefreshHistory(List<TelescienceAttemptData> history)
    {
        AttemptHistory.RemoveAllChildren();
        if (history.Count == 0)
        {
            AttemptHistory.AddChild(new Label
            {
                Text = Loc.GetString("telescience-console-empty-history"), HorizontalExpand = true,
            });
            return;
        }

        foreach (var attempt in history)
        {
            var key = attempt.Mode switch
            {
                TelescienceInteractionMode.Ping => "telescience-console-history-ping",
                TelescienceInteractionMode.Pinpoint when attempt.Hit => "telescience-console-history-hit",
                _ => "telescience-console-history-pinpoint",
            };
            var radius = attempt.Mode == TelescienceInteractionMode.Ping
                ? FormatNumber(attempt.DisplayRadius)
                : FormatNumber(attempt.PinpointRadius);
            AttemptHistory.AddChild(new Label
            {
                Text = Loc.GetString(key,
                    ("number", attempt.Id),
                    ("x", FormatCoordinate(attempt.Coordinate.X)),
                    ("y", FormatCoordinate(attempt.Coordinate.Y)),
                    ("radius", radius)),
                HorizontalExpand = true,
            });
        }
    }

    private static string FormatCoordinate(float coordinate)
        => MathF.Min(MathF.Round(coordinate, 1), TelescienceMapGeometry.MapSize - 0.1f)
            .ToString("0.#", CultureInfo.CurrentCulture);

    private static string FormatNumber(float value)
        => MathF.Round(value, 1).ToString("0.#", CultureInfo.CurrentCulture);

    private void SetStatus(string key)
        => StatusLabel.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString(key)));

    private void UpdateActions()
    {
        ExecuteButton.Disabled = _roundOver || _selectedCoordinate == null;
        NewRoundButton.Disabled = !_roundOver;
        TriesLabel.Text = Loc.GetString("telescience-console-tries",
            ("remaining", _triesRemaining),
            ("total", _maxTries));
    }
}
